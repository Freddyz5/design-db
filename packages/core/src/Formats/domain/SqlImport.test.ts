import { describe, expect, test } from "bun:test";
import { buildDiagram } from "./SchemaDraft";
import { readSql } from "./SqlImport";

function read(text: string) {
  const result = readSql(text);
  if (!result.draft) throw new Error(JSON.stringify(result.errors));
  return { ...buildDiagram(result.draft), readWarnings: result.warnings };
}

const table = (doc: ReturnType<typeof read>["diagram"], name: string) =>
  doc.tables.find((t) => t.name === name)!;

describe("readSql", () => {
  test("PostgreSQL: types, constraints, enums, comments and foreign keys", () => {
    const { diagram } = read(`
      CREATE TYPE public.post_status AS ENUM ('draft', 'published');

      CREATE TABLE IF NOT EXISTS public.users (
        id bigserial PRIMARY KEY,
        email character varying(255) NOT NULL UNIQUE,
        created_at timestamp with time zone DEFAULT now() NOT NULL
      );

      CREATE TABLE posts (
        id integer GENERATED BY DEFAULT AS IDENTITY,
        user_id bigint NOT NULL REFERENCES users ON DELETE CASCADE,
        status post_status DEFAULT 'draft'::post_status,
        price numeric(10, 2) CHECK (price > 0),
        CONSTRAINT posts_pkey PRIMARY KEY (id)
      );

      COMMENT ON TABLE users IS 'People';
      COMMENT ON COLUMN public.posts.price IS 'In cents';
      CREATE INDEX posts_user ON posts (user_id);
    `);

    expect(diagram.dialect).toBe("postgres");
    expect(diagram.enums.map((e) => [e.name, e.values])).toEqual([
      ["post_status", ["draft", "published"]],
    ]);

    const users = table(diagram, "users");
    expect(users.comment).toBe("People");
    expect(users.columns.map((c) => [c.name, c.type])).toEqual([
      ["id", "bigserial"],
      ["email", "character varying(255)"],
      ["created_at", "timestamp with time zone"],
    ]);
    expect(users.columns[0]).toMatchObject({
      primaryKey: true,
      autoIncrement: true,
    });
    expect(users.columns[1]).toMatchObject({ nullable: false, unique: true });
    expect(users.columns[2]).toMatchObject({
      default: "now()",
      nullable: false,
    });

    const posts = table(diagram, "posts");
    expect(posts.columns[0]).toMatchObject({
      primaryKey: true,
      autoIncrement: true,
    });
    expect(posts.columns[2]!.default).toBe("'draft'::post_status");
    expect(posts.columns[3]).toMatchObject({
      type: "numeric(10,2)",
      comment: "In cents",
    });

    expect(diagram.relations).toHaveLength(1);
    const [relation] = diagram.relations;
    expect(relation!.from.tableId).toBe(posts.id);
    expect(relation!.to).toEqual({
      tableId: users.id,
      columnIds: [users.columns[0]!.id],
    });
    expect(relation!.onDelete).toBe("cascade");
  });

  test("MySQL: backticks, AUTO_INCREMENT, inline ENUM and COMMENT", () => {
    const { diagram } = read(`
      CREATE TABLE \`orders\` (
        \`id\` int unsigned NOT NULL AUTO_INCREMENT,
        \`state\` ENUM('open', 'paid') NOT NULL DEFAULT 'open',
        \`total\` decimal(10,2) COMMENT 'With taxes',
        \`updated\` timestamp DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
        PRIMARY KEY (\`id\`),
        UNIQUE KEY \`orders_total\` (\`total\`),
        KEY \`idx_state\` (\`state\`)
      ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='Sales';
    `);
    expect(diagram.dialect).toBe("mysql");
    const orders = table(diagram, "orders");
    expect(orders.comment).toBe("Sales");
    expect(orders.columns[0]).toMatchObject({
      type: "int unsigned",
      primaryKey: true,
      autoIncrement: true,
    });
    expect(orders.columns[1]!.type).toBe("orders_state");
    expect(diagram.enums[0]).toMatchObject({
      name: "orders_state",
      values: ["open", "paid"],
    });
    expect(orders.columns[2]).toMatchObject({
      comment: "With taxes",
      unique: true,
    });
    expect(orders.columns[3]!.default).toBe("CURRENT_TIMESTAMP");
  });

  test("ALTER TABLE adds foreign keys, keys and columns", () => {
    const { diagram } = read(`
      CREATE TABLE a (id int, code text);
      CREATE TABLE b (id int PRIMARY KEY, a_id int);
      ALTER TABLE ONLY a ADD CONSTRAINT a_pk PRIMARY KEY (id);
      ALTER TABLE a ADD UNIQUE (code), ADD COLUMN note text NOT NULL;
      ALTER TABLE b ADD CONSTRAINT fk_b_a FOREIGN KEY (a_id) REFERENCES a (id) ON UPDATE SET NULL;
    `);
    const a = table(diagram, "a");
    expect(a.columns.map((c) => c.name)).toEqual(["id", "code", "note"]);
    expect(a.columns[0]!.primaryKey).toBe(true);
    expect(a.columns[1]!.unique).toBe(true);
    expect(a.columns[2]!.nullable).toBe(false);
    expect(diagram.relations[0]).toMatchObject({
      name: "fk_b_a",
      onUpdate: "set null",
    });
  });

  test("composite keys and table-level foreign keys", () => {
    const { diagram } = read(`
      CREATE TABLE posts (id int PRIMARY KEY);
      CREATE TABLE tags (name text PRIMARY KEY);
      CREATE TABLE post_tags (
        post_id int, tag text,
        PRIMARY KEY (post_id, tag),
        FOREIGN KEY (post_id) REFERENCES posts (id),
        FOREIGN KEY (tag) REFERENCES tags
      );
    `);
    const link = table(diagram, "post_tags");
    expect(link.columns.every((c) => c.primaryKey && !c.nullable)).toBe(true);
    expect(diagram.relations).toHaveLength(2);
  });

  test("warns about what it cannot use", () => {
    const { warnings, readWarnings, diagram } = read(`
      CREATE TABLE a (id int, x int, y int, UNIQUE (x, y));
      CREATE TABLE b (id int, a_id int REFERENCES missing (id));
      ALTER TABLE nope ADD PRIMARY KEY (id);
    `);
    expect(diagram.relations).toEqual([]);
    expect(readWarnings.map((w) => w.line)).toEqual([2, 4]);
    expect(warnings).toEqual([
      { message: 'Relation skipped: table "missing" does not exist', line: 3 },
    ]);
  });

  test("ignores comments and other statements", () => {
    const { diagram } = read(`
      -- users
      /* multi
         line */
      SET search_path = public;
      INSERT INTO t VALUES (1);
      CREATE TABLE t (id int); # mysql comment
    `);
    expect(diagram.tables.map((t) => t.name)).toEqual(["t"]);
  });

  test("reports errors with their line", () => {
    expect(readSql("CREATE TABLE a (\n  id int,\n  name text").errors).toEqual([
      { message: "Missing )", line: 3 },
    ]);
    expect(
      readSql("SELECT 1;\nCREATE TABLE b (x text DEFAULT 'oops);").errors,
    ).toEqual([{ message: "Unclosed string", line: 2 }]);
    expect(readSql("CREATE TABLE (id int);").errors[0]!.line).toBe(1);
  });
});
