import type { Column } from "../../Columns";
import { findEnum, type Diagram } from "../../Diagrams";
import type { Enum } from "../../Enums";
import type { RefAction, Relation } from "../../Relations";
import type { Dialect } from "../../shared";
import type { Table } from "../../Tables";

/**
 * Generates the SQL (DDL) of a diagram for a dialect.
 *
 * | | postgres | mysql | sqlite | generic |
 * |---|---|---|---|---|
 * | enums | CREATE TYPE | ENUM(...) | TEXT + CHECK | varchar + CHECK |
 * | auto increment | IDENTITY | AUTO_INCREMENT | AUTOINCREMENT | IDENTITY |
 * | comments | COMMENT ON | COMMENT '...' | -- | -- |
 * | foreign keys | ALTER TABLE | ALTER TABLE | inside the table | ALTER TABLE |
 *
 * Relations that point at missing tables or columns are skipped.
 */
export function toSql(
  diagram: Diagram,
  dialect: Dialect = diagram.dialect,
): string {
  const sql = new SqlWriter(diagram, dialect);
  const statements = [
    ...(dialect === "postgres"
      ? diagram.enums.map((e) => sql.createType(e))
      : []),
    ...diagram.tables.map((t) => sql.createTable(t)),
    ...(dialect === "sqlite"
      ? []
      : diagram.relations.flatMap((r) => sql.alterTableForeignKey(r))),
  ];
  return statements.length ? statements.join("\n\n") + "\n" : "";
}

class SqlWriter {
  constructor(
    private readonly diagram: Diagram,
    private readonly dialect: Dialect,
  ) {}

  createType(item: Enum): string {
    return `CREATE TYPE ${this.name(item.name)} AS ENUM (${values(item)});`;
  }

  createTable(table: Table): string {
    const primaryKey = table.columns.filter((c) => c.primaryKey);
    const inlineKey = primaryKey.length === 1 ? primaryKey[0] : undefined;

    const lines: { text: string; comment?: string }[] = table.columns.map(
      (column) => ({
        text: this.columnDefinition(column, column === inlineKey),
        ...(column.comment && this.usesLineComments
          ? { comment: column.comment }
          : {}),
      }),
    );
    if (primaryKey.length > 1) {
      lines.push({ text: `PRIMARY KEY (${this.names(primaryKey)})` });
    }
    if (this.dialect === "sqlite") {
      for (const relation of this.diagram.relations) {
        if (relation.from.tableId !== table.id) continue;
        const clause = this.foreignKey(relation);
        if (clause) lines.push({ text: clause });
      }
    }

    const body = lines
      .map(({ text, comment }, i) => {
        const comma = i < lines.length - 1 ? "," : "";
        return `  ${text}${comma}${comment ? ` -- ${oneLine(comment)}` : ""}`;
      })
      .join("\n");

    let statement = `CREATE TABLE ${this.name(table.name)} (\n${body}\n)`;
    if (this.dialect === "mysql" && table.comment) {
      statement += ` COMMENT=${literal(table.comment)}`;
    }
    statement += ";";

    if (this.usesLineComments && table.comment) {
      statement = `-- ${oneLine(table.comment)}\n${statement}`;
    }
    if (this.dialect === "postgres") {
      statement += this.commentsOn(table);
    }
    return statement;
  }

  alterTableForeignKey(relation: Relation): string[] {
    const clause = this.foreignKey(relation);
    const child = this.table(relation.from.tableId);
    if (!clause || !child) return [];
    return [`ALTER TABLE ${this.name(child.name)} ADD ${clause};`];
  }

  private get usesLineComments(): boolean {
    return this.dialect === "sqlite" || this.dialect === "generic";
  }

  private columnDefinition(column: Column, inlineKey: boolean): string {
    const enumType = findEnum(this.diagram, column.type);
    const parts = [this.name(column.name), this.columnType(column, enumType)];

    const sqliteAutoIncrement =
      this.dialect === "sqlite" &&
      inlineKey &&
      column.autoIncrement &&
      /^integer$/i.test(column.type.trim());

    if (column.autoIncrement && !sqliteAutoIncrement) {
      if (this.dialect === "mysql") parts.push("AUTO_INCREMENT");
      else if (this.dialect !== "sqlite" && !isSerial(column.type)) {
        parts.push("GENERATED BY DEFAULT AS IDENTITY");
      }
    }
    if (inlineKey) {
      parts.push(
        sqliteAutoIncrement ? "PRIMARY KEY AUTOINCREMENT" : "PRIMARY KEY",
      );
    } else if (!column.nullable) {
      parts.push("NOT NULL");
    }
    if (column.unique && !inlineKey) parts.push("UNIQUE");
    if (column.default !== undefined && column.default.trim() !== "") {
      parts.push(`DEFAULT ${column.default.trim()}`);
    }
    if (enumType && (this.dialect === "sqlite" || this.dialect === "generic")) {
      parts.push(`CHECK (${this.name(column.name)} IN (${values(enumType)}))`);
    }
    if (this.dialect === "mysql" && column.comment) {
      parts.push(`COMMENT ${literal(column.comment)}`);
    }
    return parts.join(" ");
  }

  private columnType(column: Column, enumType: Enum | undefined): string {
    if (!enumType) return column.type.trim() || "text";
    switch (this.dialect) {
      case "postgres":
        return this.name(enumType.name);
      case "mysql":
        return `ENUM(${values(enumType)})`;
      case "sqlite":
        return "TEXT";
      case "generic":
        return "varchar(255)";
    }
  }

  private commentsOn(table: Table): string {
    const lines: string[] = [];
    if (table.comment) {
      lines.push(
        `COMMENT ON TABLE ${this.name(table.name)} IS ${literal(table.comment)};`,
      );
    }
    for (const column of table.columns) {
      if (!column.comment) continue;
      lines.push(
        `COMMENT ON COLUMN ${this.name(table.name)}.${this.name(column.name)} IS ${literal(column.comment)};`,
      );
    }
    return lines.length ? "\n" + lines.join("\n") : "";
  }

  /** `[CONSTRAINT name] FOREIGN KEY (...) REFERENCES t (...) [ON ...]`. */
  private foreignKey(relation: Relation): string | undefined {
    const child = this.table(relation.from.tableId);
    const parent = this.table(relation.to.tableId);
    if (!child || !parent) return undefined;
    const from = columnsOf(child, relation.from.columnIds);
    const to = columnsOf(parent, relation.to.columnIds);
    if (!from || !to) return undefined;

    let clause = relation.name ? `CONSTRAINT ${this.name(relation.name)} ` : "";
    clause += `FOREIGN KEY (${this.names(from)}) REFERENCES ${this.name(parent.name)} (${this.names(to)})`;
    clause += action("DELETE", relation.onDelete);
    clause += action("UPDATE", relation.onUpdate);
    return clause;
  }

  private table(tableId: string): Table | undefined {
    return this.diagram.tables.find((t) => t.id === tableId);
  }

  private names(columns: Column[]): string {
    return columns.map((c) => this.name(c.name)).join(", ");
  }

  /** Quotes an identifier only when it needs it. */
  private name(name: string): string {
    if (/^[a-z_][a-z0-9_]*$/.test(name) && !RESERVED.has(name)) return name;
    if (this.dialect === "mysql") return "`" + name.replaceAll("`", "``") + "`";
    return '"' + name.replaceAll('"', '""') + '"';
  }
}

function columnsOf(table: Table, ids: string[]): Column[] | undefined {
  const columns = ids.map((id) => table.columns.find((c) => c.id === id));
  return columns.every((c) => c !== undefined)
    ? (columns as Column[])
    : undefined;
}

function action(event: "DELETE" | "UPDATE", value: RefAction): string {
  return value === "no action" ? "" : ` ON ${event} ${value.toUpperCase()}`;
}

function values(item: Enum): string {
  return item.values.map(literal).join(", ");
}

function literal(text: string): string {
  return `'${text.replaceAll("'", "''")}'`;
}

function oneLine(text: string): string {
  return text.replace(/\s*\n\s*/g, " ").trim();
}

function isSerial(type: string): boolean {
  return /^(small|big)?serial$/i.test(type.trim());
}

/** Words that must be quoted when used as names. */
const RESERVED = new Set(
  (
    "all and any array as asc between both by case cast check collate column " +
    "constraint create cross current_date current_time current_timestamp " +
    "current_user default delete desc distinct do drop else end except false " +
    "fetch for foreign from full grant group having in index inner insert " +
    "intersect into is join key leading left like limit natural not null " +
    "offset on only or order outer primary references right select " +
    "session_user some table then to trailing true union unique update user " +
    "using values when where window with"
  ).split(" "),
);
