import { describe, expect, test } from "bun:test";
import { createColumn } from "../../Columns";
import { apply, createDiagram } from "../../Diagrams";
import { createTable } from "../../Tables";
import { sampleDiagram } from "./FormatFixtures";
import { toSql } from "./SqlExport";

describe("toSql", () => {
  test("PostgreSQL", () => {
    expect(toSql(sampleDiagram(), "postgres")).toBe(
      `CREATE TYPE post_status AS ENUM ('draft', 'published');

CREATE TABLE users (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email varchar(255) NOT NULL UNIQUE
);
COMMENT ON TABLE users IS 'People who write';

CREATE TABLE posts (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id integer NOT NULL,
  status post_status NOT NULL DEFAULT 'draft',
  "order" integer,
  title text
);
COMMENT ON COLUMN posts.title IS 'Shown in lists';

ALTER TABLE posts ADD FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE;
`,
    );
  });

  test("MySQL", () => {
    expect(toSql(sampleDiagram(), "mysql")).toBe(
      `CREATE TABLE users (
  id integer AUTO_INCREMENT PRIMARY KEY,
  email varchar(255) NOT NULL UNIQUE
) COMMENT='People who write';

CREATE TABLE posts (
  id integer AUTO_INCREMENT PRIMARY KEY,
  user_id integer NOT NULL,
  status ENUM('draft', 'published') NOT NULL DEFAULT 'draft',
  \`order\` integer,
  title text COMMENT 'Shown in lists'
);

ALTER TABLE posts ADD FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE;
`,
    );
  });

  test("SQLite", () => {
    expect(toSql(sampleDiagram(), "sqlite")).toBe(
      `-- People who write
CREATE TABLE users (
  id integer PRIMARY KEY AUTOINCREMENT,
  email varchar(255) NOT NULL UNIQUE
);

CREATE TABLE posts (
  id integer PRIMARY KEY AUTOINCREMENT,
  user_id integer NOT NULL,
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published')),
  "order" integer,
  title text, -- Shown in lists
  FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
`,
    );
  });

  test("generic SQL", () => {
    const sql = toSql(sampleDiagram(), "generic");
    expect(sql).toContain("-- People who write\nCREATE TABLE users (");
    expect(sql).toContain(
      "status varchar(255) NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published'))",
    );
    expect(sql).toContain(
      "id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
    );
    expect(sql).not.toContain("CREATE TYPE");
    expect(sql).toContain("ALTER TABLE posts ADD FOREIGN KEY");
  });

  test("uses the diagram's dialect by default", () => {
    expect(toSql(sampleDiagram())).toBe(toSql(sampleDiagram(), "postgres"));
  });

  test("composite primary keys, named constraints and both actions", () => {
    const doc = apply(sampleDiagram(), {
      type: "relation.update",
      relationId: "posts_user",
      patch: { name: "fk_posts_user", onUpdate: "set null" },
    });
    const withLink = apply(doc, {
      type: "table.add",
      table: createTable({
        name: "Post Tags",
        columns: [
          createColumn({ name: "post_id", type: "integer", primaryKey: true }),
          createColumn({ name: "tag", type: "text", primaryKey: true }),
        ],
      }),
    });
    const sql = toSql(withLink, "postgres");
    expect(sql).toContain(
      'CREATE TABLE "Post Tags" (\n  post_id integer NOT NULL,\n  tag text NOT NULL,\n  PRIMARY KEY (post_id, tag)\n);',
    );
    expect(sql).toContain(
      "ADD CONSTRAINT fk_posts_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE ON UPDATE SET NULL;",
    );
  });

  test("serial columns do not get IDENTITY", () => {
    const doc = apply(createDiagram(), {
      type: "table.add",
      table: createTable({
        name: "t",
        columns: [
          createColumn({
            name: "id",
            type: "bigserial",
            primaryKey: true,
            autoIncrement: true,
          }),
        ],
      }),
    });
    expect(toSql(doc, "postgres")).toContain("  id bigserial PRIMARY KEY\n");
  });

  test("escapes quotes in names, comments and enum values", () => {
    const doc = apply(createDiagram(), {
      type: "table.add",
      table: createTable({
        name: 'a"b',
        comment: "it's",
        columns: [createColumn({ name: "x", type: "int" })],
      }),
    });
    const sql = toSql(doc, "postgres");
    expect(sql).toContain('CREATE TABLE "a""b" (');
    expect(sql).toContain("IS 'it''s';");
  });

  test("skips relations that point at something missing", () => {
    const doc = sampleDiagram();
    const broken = {
      ...doc,
      relations: [
        { ...doc.relations[0]!, to: { tableId: "gone", columnIds: ["x"] } },
      ],
    };
    expect(toSql(broken, "postgres")).not.toContain("FOREIGN KEY");
    expect(toSql(broken, "sqlite")).not.toContain("FOREIGN KEY");
  });

  test("an empty diagram gives an empty string", () => {
    expect(toSql(createDiagram())).toBe("");
  });
});
